"""svelte-blitz before damage tracking, svelte-blitz now, gpuix-svelte and Tauri 2, at 1,000 issues.

    python3 compare/results/make_compare_report.py > compare/results/compare.md

Columns and where they come from (compare/results/raw/<session>/runs.jsonl, warm-up and
aborted runs left out):
  old     svelte-blitz at 9375147 (before damage tracking), session mem-1000, 23 Nov
  new     svelte-blitz at HEAD, session j3-tauri (interleaved with Tauri), 24 Nov
  gpuix   gpuix-svelte, session mem-1000, 23 Nov
  tauri   Tauri 2, session j3-tauri (interleaved with svelte-blitz), 24 Nov
"""
import json
import statistics as st
from pathlib import Path

RAW = Path(__file__).parent / 'raw'
MB = 2**20
HELP = {'SetStoreUpdateService', 'com.apple.SafariPlatformSupport.Helper', 'SafariPlatformSupport.Helper'}


def runs(session, build):
    out = []
    for line in (RAW / session / 'runs.jsonl').open():
        r = json.loads(line)
        if r['status'] == 'ok' and not r.get('warmup') and r['build'] == build and r['size'] == 1000:
            out.append(r)
    return out


COLS = [
    ('svelte-blitz, old', runs('mem-1000', 'blitz')),
    ('svelte-blitz, now', runs('j3-tauri', 'blitz')),
    ('gpuix-svelte', runs('mem-1000', 'gpuix')),
    ('Tauri 2', runs('j3-tauri', 'tauri')),
]
ram = lambda fp: sum(p['footprint'] for p in fp['processes'] if p['name'] not in HELP) / MB
ROWS = [
    ('GPU time, ms', lambda r: r['gpu_ns'] / 1e6, 1),
    ('CPU time, ms', lambda r: r['usage']['cpu_ns'] / 1e6, 0),
    ('GPU memory at the end, MB', lambda r: r['footprint'].get('gpu', 0) / MB, 0),
    ('RAM at the end, MB', lambda r: ram(r['footprint']), 0),
    ('RAM 5 s after load, MB', lambda r: ram(r['footprint_mounted5']), 0),
]
SC = {3: 'Idle, 20 s', 4: 'A clock ticking once a second, 20 s', 8: 'Create an issue (New issue dialog)',
      9: 'Show all, then wheel-scroll the list', 10: 'Switch views: Board, Insights, Settings, Issues'}
NOTES = {
    9: '* Old scrolled half as far: the 2x trackpad bug (fixed in a789572) took the list to its end halfway '
       'through the wheel. Now, gpuix and Tauri scroll the full distance; old is not comparable on this row. '
       'GPU memory at the end depends on whether frames were still being drawn: old had stopped.',
}


def cell(vals, d):
    if not vals:
        return '—'
    m = st.median(vals)
    return f'{m:,.{d}f} ({min(vals):,.{d}f}–{max(vals):,.{d}f})' if len(vals) > 1 else f'{m:,.{d}f}'


out = []
p = out.append
p('# svelte-blitz before and now, gpuix-svelte and Tauri 2 (1,000 issues)')
p('')
p('Apple M4 Pro, macOS 27.0.1, the Tracker bench build, window 1200x800 at 2x. Cells: median (min–max). '
  'svelte-blitz now and Tauri were measured in one session, interleaved run by run (`j3-tauri`, 1 warm-up '
  '+ 3 runs each); svelte-blitz old and gpuix come from `mem-1000` (23 Nov, 1 warm-up + 3 runs). Sessions '
  'on different days drift by up to ~15%. Generated by `make_compare_report.py`; raw data in '
  '`compare/results/raw/` on this branch.')
p('')
p('**gpuix-svelte is a port** (its own widgets, a CSS subset); Tauri runs the same components and CSS as '
  'svelte-blitz. Tauri\'s numbers include its WebKit WebContent, GPU and Networking processes.')
p('')
p('**Why Tauri was missing before:** the `mem-1000` session was stopped on request on 23 Nov at 21:08 IST, '
  'right after Tauri\'s three idle runs; its other scenarios had not started (no log or record exists for '
  'them). It was not a failure of Tauri\'s runs. Every scenario ran here.')
p('')
for sc in [3, 4, 8, 9, 10]:
    p(f'## {SC[sc]}')
    p('')
    p('| | ' + ' | '.join(c for c, _ in COLS) + ' |')
    p('|---|' + '---|' * len(COLS))
    for label, fn, d in ROWS:
        cells = [cell([fn(r) for r in rs if r['scenario'] == sc], d) for _, rs in COLS]
        if sc == 9 and label.startswith('GPU time'):
            cells[0] += ' *'
        p(f'| {label} | ' + ' | '.join(cells) + ' |')
    p('')
    if sc in NOTES:
        p(NOTES[sc])
        p('')
print('\n'.join(out))
