"""Sepal before damage tracking, Sepal now, gpuix-svelte and Tauri 2, at 1,000 issues.

    python3 compare/results/make_compare_report.py > compare/results/compare.md

Columns and where they come from (compare/results/raw/<session>/runs.jsonl, warm-up and
aborted runs left out):
  old     Sepal at 9375147 (before damage tracking), session mem-1000, 23 Nov
  new     Sepal at HEAD, session final (interleaved with Tauri), 24 Nov
  gpuix   gpuix-svelte, session mem-1000, 23 Nov
  tauri   Tauri 2, session final (interleaved with Sepal), 24 Nov
"""
import json
import statistics as st
from pathlib import Path

RAW = Path(__file__).parent / 'raw'
MB = 2**20
HELP = {'SetStoreUpdateService', 'com.apple.SafariPlatformSupport.Helper', 'SafariPlatformSupport.Helper'}


def runs(session, build):
    out = []
    for line in (RAW / session / 'runs.jsonl').open():
        r = json.loads(line)
        if r['status'] == 'ok' and not r.get('warmup') and r['build'] == build and r['size'] == 1000:
            out.append(r)
    return out


COLS = [
    ('Sepal, old', runs('mem-1000', 'blitz')),
    ('Sepal, now', runs('final', 'blitz')),
    ('gpuix-svelte', runs('mem-1000', 'gpuix')),
    ('Tauri 2', runs('final', 'tauri')),
]
ram = lambda fp: sum(p['footprint'] for p in fp['processes'] if p['name'] not in HELP) / MB
ROWS = [
    ('GPU time, ms', lambda r: r['gpu_ns'] / 1e6, 1),
    ('WindowServer GPU time, ms ‡', lambda r: r['windowserver_gpu_ns'] / 1e6 if 'windowserver_gpu_ns' in r else None, 1),
    ('CPU time, ms', lambda r: r['usage']['cpu_ns'] / 1e6, 0),
    ('GPU memory at the end, MB', lambda r: r['footprint'].get('gpu', 0) / MB, 0),
    ('RAM at the end, MB', lambda r: ram(r['footprint']), 0),
    ('RAM 5 s after load, MB', lambda r: ram(r['footprint_mounted5']), 0),
]
SC = {3: 'Idle, 20 s', 4: 'A clock ticking once a second, 20 s', 8: 'Create an issue (New issue dialog)',
      9: 'Show all, then wheel-scroll the list', 10: 'Switch views: Board, Insights, Settings, Issues'}
NOTES = {
    9: '* Old scrolled half as far: the 2x trackpad bug (fixed in a789572) took the list to its end halfway '
       'through the wheel. Now, gpuix and Tauri scroll the full distance; old is not comparable on this row. '
       'GPU memory at the end depends on whether frames were still being drawn: old had stopped.',
}


def cell(vals, d):
    vals = [v for v in vals if v is not None]
    if not vals:
        return '—'
    m = st.median(vals)
    return f'{m:,.{d}f} ({min(vals):,.{d}f}–{max(vals):,.{d}f})' if len(vals) > 1 else f'{m:,.{d}f}'


out = []
p = out.append
p('# Sepal before and now, gpuix-svelte and Tauri 2 (1,000 issues)')
p('')
p('Apple M4 Pro, macOS 27.0.1, the Tracker bench build, window 1200x800 at 2x. Cells: median (min–max). '
  'Sepal now and Tauri were measured in one session, interleaved run by run (`final`, 1 warm-up '
  '+ 3 runs each); Sepal old and gpuix come from `mem-1000` (23 Nov, 1 warm-up + 3 runs). Sessions '
  'on different days drift by up to ~15%. Generated by `make_compare_report.py` from the raw data in '
  '`compare/results/raw/`, which is on the `tracker-compare` branch only (main does not have it).')
p('')
ws = lambda b, sc: st.median([r['windowserver_gpu_ns'] / 1e6 for r in COLS[b][1] if r['scenario'] == sc])
own_max = max(st.median([r['gpu_ns'] / 1e6 for r in rs if r['scenario'] == sc]) for _, rs in (COLS[1], COLS[3]) for sc in [3, 4, 8, 9, 10])
p(f'‡ **WindowServer GPU time cannot separate the apps.** It is macOS\'s WindowServer, which composites every '
  f'window on screen, read from the same counter (`accumulatedGPUTime`). In the idle runs, where neither app '
  f'draws a frame, Sepal and Tauri differ by {abs(ws(1, 3) - ws(3, 3)):,.0f} ms: more than either app\'s '
  f'own GPU time in any scenario (at most {own_max:,.0f} ms). The harness is not what adds it: these runs did not '
  f'record the screen (`--no-record`), and with an idle Sepal Tracker window open and no harness running, '
  f'WindowServer spent 382 ms per second, as in the runs (~400), against 76 ms per second with no Tracker window '
  f'and the display kept awake. It is what such a window on screen costs WindowServer on this Mac (5K display, '
  f'Stage Manager on); whether any window costs that was not measured. Recorded from 24 Nov on: — for the 23 Nov '
  f'columns.')
p('')
def released_at(r):
    """Seconds from `mounted` to the idle release, from the run's log, or None."""
    log = RAW / 'final' / 'logs' / f"{r['key']}.log"
    if not log.exists():
        return None
    mounted = released = None
    for line in log.open():
        t, _, text = line.rstrip('\n').split(' ', 2)
        if mounted is None and 'MARK mounted' in text:
            mounted = float(t)
        elif mounted is not None and 'released the kept frame' in text:
            released = float(t)
            break
    return None if released is None else (released - mounted) / 1e9


idle_runs = [r for r in COLS[1][1] if r['scenario'] in (3, 8, 9, 10)]
times = [t for t in map(released_at, idle_runs) if t is not None]
gpu5 = lambda r: r['footprint_mounted5'].get('gpu', 0) / MB
one = [r for r in idle_runs if gpu5(r) < 36]
two = [r for r in idle_runs if gpu5(r) >= 36]
def rng(vals, d=0):
    if not vals:
        return '—'
    lo, hi = f'{min(vals):,.{d}f}', f'{max(vals):,.{d}f}'
    return lo if lo == hi else f'{lo}-{hi}'
idle_end = lambda rs: [ram(r['footprint']) for r in rs if r['scenario'] == 3]
p(f'**Sepal\'s memory after it goes idle comes in two sizes.** It lets go of its kept frame and depth '
  f'buffer 2 s after its last frame ({rng(times, 2)} s after load in {len(times)} of {len(idle_runs)} runs of '
  f'idle, dialog, scroll and views; the clock never goes 2 s without a frame). What remains 5 s after load is '
  f'either {rng([gpu5(r) for r in one])} MB of GPU memory and {rng([ram(r["footprint_mounted5"]) for r in one])} MB '
  f'of RAM ({len(one)} runs) or {rng([gpu5(r) for r in two])} and {rng([ram(r["footprint_mounted5"]) for r in two])} '
  f'MB ({len(two)} runs), from launch to launch: the window\'s surface keeps one or two 2400x1600 drawables '
  f'(15 MB each) resident (footprint\'s IOSurface category). At the end of the idle runs: '
  f'{rng(idle_end(one))} MB of RAM with one, {rng(idle_end(two))} MB with two.')
p('')
gpu_end = lambda col, sc: st.median([r['footprint'].get('gpu', 0) / MB for r in COLS[col][1] if r['scenario'] == sc])
deltas = ', '.join(f"{name} {gpu_end(1, sc) - gpu_end(0, sc):+.0f} MB" for name, sc in [('clock', 4), ('dialog', 8), ('views', 10)])
p(f'**GPU memory while active is higher than on 23 Nov** ({deltas}, now against old, at the end of the '
  f'scenario). About 15 MB of that is the kept frame, the 2400x1600 BGRA8 texture damage tracking draws each frame '
  f'over (the old build drew straight into the window\'s surface); it is let go 2 s after the last frame. The '
  f'rest of GPU memory is mostly the driver\'s, which varies between sessions.')
p('')
p('**gpuix-svelte is a port** (its own widgets, a CSS subset); Tauri runs the same components and CSS as '
  'Sepal. Tauri\'s numbers include its WebKit WebContent, GPU and Networking processes.')
p('')
p('**Why Tauri was missing before:** the `mem-1000` session was stopped on request on 23 Nov at 21:08 IST, '
  'right after Tauri\'s three idle runs; its other scenarios had not started (no log or record exists for '
  'them). It was not a failure of Tauri\'s runs. Every scenario ran here.')
p('')
for sc in [3, 4, 8, 9, 10]:
    p(f'## {SC[sc]}')
    p('')
    p('| | ' + ' | '.join(c for c, _ in COLS) + ' |')
    p('|---|' + '---|' * len(COLS))
    for label, fn, d in ROWS:
        cells = [cell([fn(r) for r in rs if r['scenario'] == sc], d) for _, rs in COLS]
        if sc == 9 and label.startswith('GPU time'):
            cells[0] += ' *'
        p(f'| {label} | ' + ' | '.join(cells) + ' |')
    p('')
    if sc in NOTES:
        p(NOTES[sc])
        p('')
print('\n'.join(out))
