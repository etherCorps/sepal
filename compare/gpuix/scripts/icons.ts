// One-off: the Lucide icons the Tracker uses, from @lucide/svelte 1.77.0 in examples/tracker, as SVG
// markup strings for <svg source>. Run with `bun scripts/icons.ts > src/icons.ts`.
import { readFileSync } from 'node:fs';

const NAMES = ['layout-list', 'circle-user-round', 'square-kanban', 'chart-column', 'settings', 'plus', 'chevron-down', 'chevron-right', 'x', 'search', 'arrow-down', 'arrow-up', 'link', 'keyboard', 'undo-2', 'rows-3', 'info', 'circle-alert'];
const dir = '../../examples/tracker/node_modules/@lucide/svelte/dist/icons';
console.log('// Generated by scripts/icons.ts from @lucide/svelte 1.77.0 (ISC). Each icon as Lucide draws it:');
console.log('// a 24-unit viewBox, stroke currentColor, round caps and joins; `icon(name, stroke)` sets the width.\n');
console.log('const BODY = {');
for (const name of NAMES) {
	// Some names are aliases: icons/<name>.js re-exports the real file.
	const alias = /from "\.\/(.+)\.svelte"/.exec(readFileSync(`${dir}/${name}.js`, 'utf8'));
	const source = readFileSync(`${dir}/${alias ? alias[1] : name}.svelte`, 'utf8');
	const data = JSON.parse(/__iconData = (\{.*?\});/.exec(source)![1]);
	const body = data.node.map(([tag, attrs]: [string, Record<string, string>]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`).join('');
	console.log(`\t'${name}': '${body}',`);
}
console.log('};\n');
console.log(`export type IconName = keyof typeof BODY;

/** Lucide's markup with the stroke width the Tracker passes (\`strokeWidth={1.75}\`). */
export function icon(name: IconName, stroke = 1.75): string {
	return \`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="\${stroke}" stroke-linecap="round" stroke-linejoin="round">\${BODY[name]}</svg>\`;
}`);
